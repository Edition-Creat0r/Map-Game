// Freeze trusted existing rules for server execution; never evaluates user code.
const fs = require("node:fs"),
  path = require("node:path"),
  crypto = require("node:crypto");
const root = path.resolve(__dirname, "../..");
const files = [
  "buildings.js",
  "industrial/catalog-data.js",
  "industrial/registry.js",
  "industrial/integration.js",
  "industrial/player-materials-data.js",
  "industrial/research-data.js",
  "industrial/progression.js",
  "economy_model.js",
  "world_terrain.js",
];
const sources = files.map((file) => ({
  file,
  text: fs.readFileSync(path.join(root, file), "utf8"),
}));
const hashes = Object.fromEntries(
  sources.map(
    (s) => [s.file, crypto.createHash("sha256").update(s.text).digest("hex")],
  ),
);
const hash = crypto.createHash("sha256").update(JSON.stringify(hashes)).digest(
  "hex",
);
const manifest = {
  version: 1,
  hash,
  seed: 734221,
  files: hashes,
  sourceCommit: "bc8945d3deeb99d1074d341c1eccd11ad59a6d82",
};
const script =
  `// Generated by build-bundle.cjs from trusted, unchanged game sources.\nexport const manifest=${
    JSON.stringify(manifest, null, 2)
  };\nconst sources=${
    JSON.stringify(sources)
  };\nexport function createEngine(seed=manifest.seed){\n if(!Number.isInteger(seed)||seed===0)throw Error('Invalid canonical seed');\n const scope={}; const storage={getItem:k=>k==='mapgame_world_seed'?String(seed):null};\n for(const source of sources)new Function('window','globalThis','module','localStorage','console',source.text)(scope,scope,undefined,storage,{log(){}});\n return {model:scope.mapGameEconomyModel,progression:scope.mapGameProgression,registry:scope.mapGameIndustrialRegistry,defs:scope.mapGameBuildings.CATALOG.filter(d=>d.economy),terrain:scope.mapGameSharedTerrain};\n}\n`;
fs.writeFileSync(path.join(__dirname, "generated/rules.mjs"), script);
fs.writeFileSync(
  path.join(__dirname, "generated/manifest.json"),
  JSON.stringify(manifest, null, 2) + "\n",
);
console.log(hash);
